"""Turn an experiment description into a Kaggle job YAML (the format read by launch.py).

An experiment is a YAML file with the keys
  name, branch, gpu, datasets, kernels, inputs   copied to the job unchanged (gpu defaults to true)
  description   one or more lines written as the comment at the top of the job
  setup         shell commands run first, in order (unzipping inputs, links)
  chains        list of chains; a chain is a list of commands run one after another on one GPU

A chain command is written as for scripts/run.py, `<method> <stage> [args...]`, and becomes
`python methods/<method>/<stage>.py [args...]`. Any other command is copied unchanged.
`{NAME}` refers to the input NAME as in a job; every other brace is escaped for the kernel's
str.format, so shell variables are written as usual (`${var}`, not `${{var}}`).

Chains are assigned to the GPUs in turn (chain i to GPU i mod --gpus). All chains of one GPU run
in one background shell with `set -e` and CUDA_VISIBLE_DEVICES=<gpu>, writing runs/gpu<gpu>.log.
The job waits for every GPU, prints the last two lines of each log and fails if any GPU failed.

Usage:
  python scripts/kaggle/make_job.py scripts/kaggle/experiments/<name>.yaml [--out FILE] [--force]
  python scripts/kaggle/make_job.py <experiment> --compare scripts/kaggle/jobs/<job>.yaml
"""
import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
JOBS = ROOT / "scripts" / "kaggle" / "jobs"
COPIED = ("name", "branch", "gpu", "datasets", "kernels", "inputs")
PLAIN = re.compile(r"[A-Za-z0-9_./-]+")


def translate(command):
    words = command.split()
    if len(words) >= 2 and (ROOT / "methods" / words[0] / f"{words[1]}.py").exists():
        return " ".join(["python", f"methods/{words[0]}/{words[1]}.py", *words[2:]])
    return command


def escape(command, inputs):
    escaped = command.replace("{", "{{").replace("}", "}}")
    return re.sub(r"\{\{(\w+)\}\}", lambda m: "{" + m.group(1) + "}" if m.group(1) in inputs else m.group(0), escaped)


def parallel(chains, n_gpus):
    """Lines of one shell command running the chains on n_gpus GPUs in parallel."""
    per_gpu = [[] for _ in range(min(n_gpus, len(chains)))]
    for i, chain in enumerate(chains):
        per_gpu[i % len(per_gpu)].extend(chain)
    lines = []
    for gpu, commands in enumerate(per_gpu):
        lines.append(f"(set -e; export CUDA_VISIBLE_DEVICES={gpu};")
        lines += [f"{command};" for command in commands]
        lines.append(f") > runs/gpu{gpu}.log 2>&1 & p{gpu}=$!;")
    gpus = range(len(per_gpu))
    lines.append(" ".join(f"wait $p{g}; r{g}=$?;" for g in gpus))
    lines.append("tail -n 2 " + " ".join(f"runs/gpu{g}.log" for g in gpus) + ";")
    lines.append("exit $((" + " || ".join(f"r{g} != 0" for g in gpus) + "))")
    return lines


def make_job(experiment, n_gpus):
    inputs = experiment.get("inputs", {})
    job = {key: experiment[key] for key in COPIED if key in experiment}
    job.setdefault("gpu", True)
    chains = [[escape(translate(c), inputs) for c in chain] for chain in experiment["chains"]]
    setup = [escape(c, inputs) for c in experiment.get("setup", [])]
    return job, setup, parallel(chains, n_gpus)


def scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    return value if PLAIN.fullmatch(str(value)) else json.dumps(value)


def render(experiment, job, setup, lines):
    out = [f"# {line}" for line in str(experiment.get("description", "")).strip().splitlines()]
    out.append("# Generated by scripts/kaggle/make_job.py; edit the experiment file and regenerate.")
    for key in COPIED:
        if key not in job:
            continue
        value = job[key]
        if isinstance(value, dict):
            out.append(f"{key}:")
            out += [f"  {k}: {scalar(v)}" for k, v in value.items()]
        elif isinstance(value, list):
            out.append(f"{key}:")
            out += [f"  - {scalar(v)}" for v in value]
        else:
            out.append(f"{key}: {scalar(value)}")
    out.append("commands:")
    out += [f"  - {json.dumps(c)}" for c in setup]
    out.append("  - >-")
    out += [f"    {line}" for line in lines]
    text = "\n".join(out) + "\n"
    loaded = yaml.safe_load(text)
    assert loaded["commands"] == setup + [" ".join(lines)], "rendered YAML does not round-trip"
    for command in loaded["commands"]:
        command.format(**{key: "" for key in job.get("inputs", {})})
    return text


def gpu_chains(command):
    """Commands per GPU in a parallel command of the form written by this script."""
    out = {}
    for gpu, body in re.findall(r"\(set -e; export CUDA_VISIBLE_DEVICES=(\d+);(.*?)\) > runs/gpu\d+\.log", command):
        out[int(gpu)] = [" ".join(c.split()) for c in body.split(";") if c.strip()]
    return out


def compare(text, path):
    with open(path) as f:
        reference = yaml.safe_load(f)
    job = yaml.safe_load(text)
    differences = []
    for key in COPIED:
        if job.get(key) != reference.get(key):
            differences.append(f"{key}: {job.get(key)!r} != {reference.get(key)!r}")
    ours, theirs = job["commands"], reference["commands"]
    if ours[:-1] != theirs[:-1]:
        differences.append(f"setup commands differ:\n  {ours[:-1]}\n  {theirs[:-1]}")
    if gpu_chains(ours[-1]) != gpu_chains(theirs[-1]):
        differences.append(f"GPU chains differ:\n  {gpu_chains(ours[-1])}\n  {gpu_chains(theirs[-1])}")
    tail = lambda c: c[c.rindex(") > runs/gpu"):].split("& ", 1)[-1] if ") > runs/gpu" in c else c
    if tail(ours[-1]) != tail(theirs[-1]):
        print(f"note: wait/exit lines differ\n  generated: {tail(ours[-1])}\n  reference: {tail(theirs[-1])}")
    for line in differences:
        print(line)
    print(f"{len(differences)} differences in name, branch, inputs, setup and per-GPU commands")
    return not differences


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("experiment")
    parser.add_argument("--out", default=None, help="job file to write (default: scripts/kaggle/jobs/<experiment name>)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing job file")
    parser.add_argument("--gpus", type=int, default=2)
    parser.add_argument("--compare", default=None, metavar="JOB",
                        help="compare the generated job with an existing job file instead of writing it")
    parser.add_argument("--print", action="store_true", help="print the job instead of writing it")
    args = parser.parse_args()
    with open(args.experiment) as f:
        experiment = yaml.safe_load(f)
    text = render(experiment, *make_job(experiment, args.gpus))
    if args.compare:
        sys.exit(0 if compare(text, args.compare) else 1)
    if args.print:
        print(text, end="")
        return
    out = Path(args.out) if args.out else JOBS / Path(args.experiment).name
    if out.exists() and not args.force:
        raise SystemExit(f"{out} exists; pass --force to overwrite or --out to write elsewhere")
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
