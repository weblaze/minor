"""Collect and compare evaluation runs of every method.

Evaluation scripts of all methods write a run directory with `results.json`, `features.npz`,
`config.yaml` and `meta.json`. This script reads those directories, whatever method produced
them, and reports them in one format.

  table      one row per evaluated output: method, variant, audio code, seed, tag, structure and
             distribution scores, commit. Written as CSV and as a Markdown table.
  agreement  for runs that share the same test tracks: Pearson correlation between the image
             distance matrices of two runs (how similar the two mappings are as geometries) and
             the correlation of each run's image distances with the audio distances of the other
             run (how much of one audio code's structure the other run preserves).

Run directories are searched under the given roots (default: runs/), including fetched Kaggle
output (runs/kaggle/<job>/runs/).

Usage:
  python scripts/results.py table [--roots runs] [--out docs/results]
  python scripts/results.py agreement [--roots runs] [--match s1_eval q1_eval]
"""
import argparse
import csv
import json
from pathlib import Path

import numpy as np
import yaml

from abstraction.metrics.structure import distance_matrix

COLUMNS = ["method", "variant", "output", "code", "seed", "tag", "mantel_r", "mantel_rho", "knn_overlap",
           "trustworthiness", "frechet_distance", "participation_ratio", "n_distinct", "commit", "run"]


def find_runs(roots):
    runs = []
    for root in roots:
        for path in sorted(Path(root).rglob("results.json")):
            if "_smoke" not in path.parent.name and "_eval_" in path.parent.name:
                runs.append(path.parent)
    return runs


def identity(run):
    config = yaml.safe_load(open(run / "config.yaml")) if (run / "config.yaml").exists() else {}
    meta = json.load(open(run / "meta.json")) if (run / "meta.json").exists() else {}
    system, info = config.get("system", {}), config.get("run", {})
    code = info.get("code") or info.get("code_variant") or config.get("audio_code", {}).get("variant") or "mean"
    return {"method": run.name.split("_")[0], "seed": system.get("seed"), "tag": system.get("tag") or "",
            "code": code, "commit": (meta.get("git_commit") or "")[:7], "run": run.name}


def rows_of(run):
    results = json.load(open(run / "results.json"))
    base = identity(run)
    base["variant"] = results.get("variant", "")
    base["code"] = results.get("code_variant", base["code"])
    if results.get("mapper_seed") is not None:
        base["seed"] = results["mapper_seed"]
    outputs = {key: results[key] for key in ("direct", "painting") if key in results} or {"image": results}
    rows = []
    for name, block in outputs.items():
        structure, dist = block.get("structure", {}), block.get("image_distribution", {})
        generated = dist.get("generated", dist)
        rows.append({**base, "output": name,
                     "mantel_r": structure.get("mantel_pearson"), "mantel_rho": structure.get("mantel_spearman"),
                     "knn_overlap": structure.get("knn_overlap"), "trustworthiness": structure.get("trustworthiness"),
                     "frechet_distance": generated.get("frechet_distance"),
                     "participation_ratio": dist.get("participation_ratio", dist.get("participation_ratio_generated")),
                     "n_distinct": block.get("n_distinct_paintings", "")})
    return rows


def fmt(value):
    if isinstance(value, float):
        return f"{value:.3f}" if abs(value) < 10 else f"{value:.1f}"
    return "" if value is None else str(value)


def table(args):
    rows = [row for run in find_runs(args.roots) for row in rows_of(run)]
    rows.sort(key=lambda r: (r["method"], r["code"], r["variant"], str(r["tag"]), str(r["seed"]), r["output"]))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out.with_suffix(".csv"), "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    lines = ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    lines += ["| " + " | ".join(fmt(row[c]) for c in COLUMNS) + " |" for row in rows]
    out.with_suffix(".md").write_text(
        "# Results\n\nGenerated by `scripts/results.py table` from the run directories. Do not edit by hand.\n\n"
        + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} rows from {len(find_runs(args.roots))} runs -> {out.with_suffix('.csv')}, {out.with_suffix('.md')}")


def features_of(run):
    data = np.load(run / "features.npz")
    key = "image_features" if "image_features" in data.files else "painting_features"
    return data["track_ids"], data["audio_codes"], data[key]


def agreement(args):
    runs = [run for run in find_runs(args.roots) if (run / "features.npz").exists()
            and (not args.match or any(m in run.name for m in args.match))]
    loaded, reference = [], None
    for run in runs:
        ids, codes, features = features_of(run)
        if reference is None:
            reference = ids
        if len(ids) == len(reference) and (ids == reference).all():
            iu = np.triu_indices(len(ids), k=1)
            loaded.append((run.name, distance_matrix(codes)[iu], distance_matrix(features)[iu]))
    r = lambda a, b: float(np.corrcoef(a, b)[0, 1])
    print(f"{len(loaded)} runs on the same {len(reference)} tracks")
    print("run | r with own audio code | " + " | ".join(str(i) for i in range(len(loaded))))
    for i, (name, d_audio, d_image) in enumerate(loaded):
        print(f"{i} {name} | {r(d_audio, d_image):.3f} | " + " | ".join(f"{r(d_image, other):.2f}" for _, _, other in loaded))
    print("\nimage distances of run (row) against audio distances of run (column)")
    for i, (name, _, d_image) in enumerate(loaded):
        print(f"{i} | " + " | ".join(f"{r(d_image, other):.2f}" for _, other, _ in loaded))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("table", "agreement"):
        p = sub.add_parser(name)
        p.add_argument("--roots", nargs="+", default=["runs"])
        if name == "table":
            p.add_argument("--out", default="docs/results")
        else:
            p.add_argument("--match", nargs="+", default=None)
    args = parser.parse_args()
    {"table": table, "agreement": agreement}[args.command](args)


if __name__ == "__main__":
    main()
